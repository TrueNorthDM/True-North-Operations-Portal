-- 053_monday_webhook_secret.sql
--
-- Gives the Monday webhook a credential. Until now POST /api/monday/webhook
-- accepted anyone: verified in production by posting {"event":{}} with no
-- headers and getting 200 {"ok":true} back, from an endpoint that runs as
-- service_role and can write to the database and back into Monday.
--
-- WHY A URL SECRET AND NOT A SIGNATURE. Monday's docs are explicit that the JWT
-- in the Authorization header only exists when the webhook was created with an
-- integration app token. These two webhooks (AAAF and HFA) were created with a
-- personal API token, and the account has no app at all: Developer Center ->
-- My apps is empty. So there is no signing secret in existence to check
-- against, and monday_signing_secret was a column for a check that could never
-- run. An unguessable path segment is the standard fallback for unsigned
-- webhook providers.
--
-- The upgrade path stays open: create a Monday app with an integration feature,
-- generate an OAuth token, recreate the webhooks with it, and the JWT becomes
-- available. That is a bigger job and was weighed against this one; this is the
-- one that closes the hole today.
--
-- The secret is generated by the app (Settings -> APIs & tokens -> Generate),
-- never typed, so it starts as NULL here. webhookSecretMatches() fails closed
-- on NULL: the secret URL accepts nothing until one exists.

ALTER TABLE app_settings ADD COLUMN IF NOT EXISTS monday_webhook_secret text;

-- Dead column. It was added in 002 for the JWT path above, nothing ever wrote
-- to it (which is how the endpoint stayed unauthenticated: the route treated
-- "no secret configured" as "skip the check"), and it cannot be populated
-- without a Monday app.
ALTER TABLE app_settings DROP COLUMN IF EXISTS monday_signing_secret;
